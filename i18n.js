    const switcherEl = document.getElementById("lang-switcher");

    window.applyPortfolioLanguage = function (langCode) {
        const lang = TRANSLATIONS[langCode] ? langCode : "en";
        const dict = TRANSLATIONS[lang];

        document.title = dict.meta_title;
        document.documentElement.lang = lang;
        document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";

        document.querySelectorAll("[data-i18n]").forEach(el => {
            const key = el.getAttribute("data-i18n");
            if (dict[key]) el.textContent = dict[key];
        });

        document.querySelectorAll("[data-i18n-html]").forEach(el => {
            const key = el.getAttribute("data-i18n-html");
            if (dict[key]) el.innerHTML = dict[key];
        });

        if (switcherEl) switcherEl.value = lang;
        localStorage.setItem("artyom_portfolio_lang", lang);
    };

    if (switcherEl) {
        switcherEl.addEventListener("change", (e) => {
            window.applyPortfolioLanguage(e.target.value);
        });
    }

    async function initPortfolioLanguage() {
        const saved = localStorage.getItem("artyom_portfolio_lang");
        if (saved && TRANSLATIONS[saved]) {
            window.applyPortfolioLanguage(saved);
            return;
        }

        // 1. Мгновенный старт по языку браузера (без мерцания)
        const navLang = (navigator.language || "en").slice(0, 2).toLowerCase();
        const initialLang = TRANSLATIONS[navLang] ? navLang : "en";
        window.applyPortfolioLanguage(initialLang);

        // 2. Уточнение страны посетителя по IP
        try {
            const res = await fetch("https://ipwho.is/");
            if (!res.ok) return;
            const geo = await res.json();
            if (geo && geo.success && geo.country_code) {
                const detectedLang = COUNTRY_TO_LANG[geo.country_code] || "en";
                // Не перезаписываем в localStorage как ручной выбор, чтобы при переезде/VPN сработало снова
                const prevSaved = localStorage.getItem("artyom_portfolio_lang");
                window.applyPortfolioLanguage(detectedLang);
                if (!prevSaved) {
                    localStorage.removeItem("artyom_portfolio_lang");
                }
            }
        } catch (_) {
            // Если запрос заблокирован AdBlock/сетью, остаётся язык браузера
        }
    }

    if (document.readyState === "loading") {
        document.addEventListener("DOMContentLoaded", initPortfolioLanguage);
    } else {
        initPortfolioLanguage();
    }
